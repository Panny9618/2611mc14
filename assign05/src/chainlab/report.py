"""Write the simulation outputs: event log, header dump and branch diagram (SVG)."""

from __future__ import annotations

import os
from html import escape

from .block import bits_of


def write_outputs(sim) -> None:
    out = sim.out_dir
    with open(os.path.join(out, "header_dump.txt"), "w", encoding="utf-8") as f:
        f.write(f"Block 1 (mined by MinerA, contains Alice pays Bob 85)\n\n{sim.header_example.dump()}\n")
    with open(os.path.join(out, "fork_log.md"), "w", encoding="utf-8") as f:
        f.write(log_markdown(sim))
    with open(os.path.join(out, "fork_diagram.svg"), "w", encoding="utf-8") as f:
        f.write(diagram_svg(sim))


def log_markdown(sim) -> str:
    rows = ["| Block | Miner | Bits | Note | Result | Details | Active tip after (height, work) |",
            "|---|---|---:|---|---|---|---|"]
    for r in sim.log:
        if r["status"] == "REORG":
            det = f"disconnected {', '.join(r['disconnected'])}; connected {', '.join(r['connected'])}"
            if r["conflicted"] or r["resurrected"]:
                det += f"; stale txs: {r['resurrected']} back to mempool, {r['conflicted']} dropped as conflicting"
        elif r["code"]:
            det = f"`{r['code']}` {r['reason']}" + ("; chain & UTXO set unchanged" if r["unchanged"] else "")
        else:
            det = r["reason"] or ""
        rows.append(f"| {r['label']} | {r['miner']} | {r['bits']} | {r['note']} | **{r['status']}** | {escape(det)} "
                    f"| {r['tip']} (h={r['tip_height']}, {r['tip_work']:,}) |")
    checks = "\n".join(f"- {'✅' if v else '❌'} {k}" for k, v in sim.checks.items())
    chain = " → ".join(sim.labels.get(h, h[:6]) for h in sim.node.active)
    return ("# Fork simulation log\n\nGenerated by `chain simulate`. Work of one block = 2^bits "
            "(16 bits = 65,536; 17 bits = 131,072; 19 bits = 524,288).\n\n"
            + "\n".join(rows) + f"\n\n**Final active chain:** {chain}\n\n**Final balances:** {sim.balances()}\n\n"
            f"## Checks\n\n{checks}\n")


def diagram_svg(sim) -> str:
    n = sim.node
    active = set(n.active)
    lane: dict[str, int] = {}
    used: set[tuple[int, int]] = set()
    entries = sorted(n.entries.values(), key=lambda e: e.seq)
    for e in entries:
        if e.hash in active:
            lane[e.hash] = 0
            used.add((0, e.height))
    next_lane = 1
    for e in entries:
        if e.hash in lane:
            continue
        pl = lane.get(e.parent, 0)
        if pl != 0 and (pl, e.height) not in used:
            lane[e.hash] = pl
        else:
            lane[e.hash] = next_lane
            next_lane += 1
        used.add((lane[e.hash], e.height))

    BW, BH, GX, GY, X0, Y0 = 134, 62, 160, 92, 30, 80
    max_h = max(e.height for e in entries)
    W = X0 * 2 + (max_h + 1) * GX
    H = Y0 + next_lane * GY + 120
    pos = {e.hash: (X0 + e.height * GX, Y0 + lane[e.hash] * GY) for e in entries}
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" font-family="Helvetica, Arial, sans-serif">',
         f'<rect width="{W}" height="{H}" fill="#fff"/>',
         f'<text x="{X0}" y="32" font-size="19" font-weight="bold" fill="#18181b">Competing branches seen by the node (x = height)</text>',
         f'<text x="{X0}" y="54" font-size="13" fill="#52525b">Active chain = most cumulative work. Numbers in brackets = arrival order.</text>']
    for h in range(max_h + 1):
        s.append(f'<text x="{X0 + h * GX + BW / 2}" y="{H - 82}" text-anchor="middle" font-size="12" fill="#71717a">h={h}</text>')
    for e in entries:
        if e.parent:
            x1, y1 = pos[e.parent]
            x2, y2 = pos[e.hash]
            on = e.hash in active
            s.append(f'<path d="M{x1 + BW} {y1 + BH / 2} C{x1 + BW + 20} {y1 + BH / 2} {x2 - 20} {y2 + BH / 2} {x2} {y2 + BH / 2}" '
                     f'fill="none" stroke="{"#1d4ed8" if on else "#a1a1aa"}" stroke-width="{3 if on else 1.6}"/>')
    for e in entries:
        x, y = pos[e.hash]
        if e.invalid:
            fill, stroke = "#fee2e2", "#b91c1c"
        elif e.hash in active:
            fill, stroke = "#dbeafe", "#1d4ed8"
        else:
            fill, stroke = "#f4f4f5", "#71717a"
        lab = sim.labels.get(e.hash, e.hash[:6])
        s.append(f'<rect x="{x}" y="{y}" width="{BW}" height="{BH}" rx="8" fill="{fill}" stroke="{stroke}" stroke-width="2"/>')
        s.append(f'<text x="{x + 8}" y="{y + 18}" font-size="14" font-weight="bold" fill="#18181b">{escape(lab)} '
                 f'<tspan font-weight="normal" font-size="11" fill="#52525b">[{e.seq}] {escape(e.miner)}</tspan></text>')
        s.append(f'<text x="{x + 8}" y="{y + 35}" font-size="11" font-family="Menlo, Consolas, monospace" fill="#3f3f46">{e.hash[:13]}…</text>')
        sub = f"{bits_of(e.header.target):.0f} bits · work {e.work:,}" if not e.invalid else f"INVALID: {e.invalid}"
        s.append(f'<text x="{x + 8}" y="{y + 52}" font-size="10.5" fill="{"#b91c1c" if e.invalid else "#3f3f46"}">{escape(sub)}</text>')
    ly = H - 52
    for k, (fill, stroke, txt) in enumerate([("#dbeafe", "#1d4ed8", "active (most-work) chain"),
                                             ("#f4f4f5", "#71717a", "valid but stale branch"),
                                             ("#fee2e2", "#b91c1c", "rejected during connection")]):
        lx = X0 + k * 250
        s.append(f'<rect x="{lx}" y="{ly - 12}" width="22" height="15" rx="3" fill="{fill}" stroke="{stroke}" stroke-width="2"/>')
        s.append(f'<text x="{lx + 30}" y="{ly}" font-size="13" fill="#3f3f46">{txt}</text>')
    s.append(f'<text x="{X0}" y="{ly + 26}" font-size="12" fill="#52525b">Blocks failing context-free checks (bad PoW, wrong Merkle root) '
             f'are rejected before indexing, so they do not appear here. "work" = cumulative chain work.</text>')
    s.append("</svg>")
    return "\n".join(s)
